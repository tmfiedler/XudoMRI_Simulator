function displayImagesCore(hImages,inputInfo,displayInfo,selectView,geoData)

% Pixel centers are one-based; voxel j occupies [j-0.5,j+0.5].

    if length(inputInfo.FOV)<2
       inputInfo.FOV(2)=inputInfo.FOV;
    end
    if inputInfo.FOV_flag==1
        inputInfo.FOV=rot90(inputInfo.FOV,2);
    end

    tempBool = isfield(displayInfo,'HideFOVOverlay') && displayInfo.HideFOVOverlay;
    is3DRadOverlay = isfield(displayInfo,'ActiveSequenceName') && ...
        usesRadial3DWorkflow(displayInfo.ActiveSequenceName);

    axialIndex = clampIndex(inputInfo.currentZ+displayInfo.geoDeltaZ, size(geoData,3));
    sagittalIndex = clampIndex(inputInfo.currentX+displayInfo.geoDeltaX, size(geoData,1));
    coronalIndex = clampIndex(inputInfo.currentY+displayInfo.geoDeltaY, size(geoData,2));

    axialSlice = padWithZeros(squeeze(geoData(:, :, axialIndex)), [displayInfo.padAxial_X, displayInfo.padAxial_Y]);
    sagittalSlice = padWithZeros(squeeze(geoData(sagittalIndex, :, :)), [displayInfo.padSagittal_Y, displayInfo.padSagittal_Z]);
    coronalSlice = padWithZeros(squeeze(geoData(:, coronalIndex, :)), [displayInfo.padCoronal_X, displayInfo.padCoronal_Z]);

    switch displayInfo.Scale
        case 1 % Linear
            imageMatrixA = rot90(axialSlice); % for XY
            imageMatrixS = rot90(sagittalSlice); % for YZ
            imageMatrixC = rot90(coronalSlice); % for XZ
        case 2 % Log
            imageMatrixA = log(max(rot90(axialSlice), realmin('double'))); % for XY
            imageMatrixS = log(max(rot90(sagittalSlice), realmin('double'))); % for YZ
            imageMatrixC = log(max(rot90(coronalSlice), realmin('double'))); % for XZ
    end

    % Reverse rows using each actual padded raster, including non-square grids.
    % These local lengths affect overlays only; input padding/data stay unchanged.
    displayInfo.imageLengthXY = size(imageMatrixA,1);
    displayInfo.imageLengthYZ = size(imageMatrixS,1);
    displayInfo.imageLengthXZ = size(imageMatrixC,1);

    renderSlice(hImages.hAxlImage, imageMatrixA);
    renderSlice(hImages.hSagImage, imageMatrixS);
    renderSlice(hImages.hCrlImage, imageMatrixC);

    switch selectView
        case 1
            hImages.Axial.volume = rectangle('Parent',hImages.hAxlImage,'position',...
                [inputInfo.minX+displayInfo.geoDeltaX+displayInfo.padAxial_X-.5,...
                displayInfo.imageLengthXY-(inputInfo.maxY+displayInfo.geoDeltaY+displayInfo.padAxial_Y)+.5,...
                inputInfo.maxX-inputInfo.minX+1, inputInfo.maxY-inputInfo.minY+1],...
                'EdgeColor','r');
            hImages.Axial.center = rectangle('Parent',hImages.hAxlImage,'position',...
                [inputInfo.ctrX+displayInfo.geoDeltaX+displayInfo.padAxial_X-3/2,...
                displayInfo.imageLengthXY-(inputInfo.ctrY+displayInfo.geoDeltaY+displayInfo.padAxial_Y)+1-3/2,...
                3, 3],'EdgeColor','y','FaceColor','y');

            hImages.Axial.slice = createFOVOverlay(hImages.hAxlImage,tempBool,...
                getDisplayedFOVPosition('Axial',selectView,inputInfo,displayInfo,is3DRadOverlay));

            hImages.Sagittal.volume = rectangle('Parent',hImages.hSagImage,'position',...
                [inputInfo.minY+displayInfo.geoDeltaY+displayInfo.padSagittal_Y-.5,...
                displayInfo.imageLengthYZ-(inputInfo.maxZ+displayInfo.geoDeltaZ+displayInfo.padSagittal_Z)+.5,...
                inputInfo.maxY-inputInfo.minY+1, inputInfo.maxZ-inputInfo.minZ+1],...
                'EdgeColor','r');
            hImages.Sagittal.center = rectangle('Parent',hImages.hSagImage,'position',...
                [inputInfo.ctrY+displayInfo.geoDeltaY+displayInfo.padSagittal_Y-3/2,...
                displayInfo.imageLengthYZ-(inputInfo.ctrZ+displayInfo.geoDeltaZ+displayInfo.padSagittal_Z)+1-3/2,...
                3, 3],'EdgeColor','y','FaceColor','y');

            hImages.Sagittal.slice = createFOVOverlay(hImages.hSagImage,tempBool,...
                getDisplayedFOVPosition('Sagittal',selectView,inputInfo,displayInfo,is3DRadOverlay));

            hImages.Coronal.volume = rectangle('Parent',hImages.hCrlImage,'position',...
                [inputInfo.minX+displayInfo.geoDeltaX+displayInfo.padCoronal_X-.5,...
                displayInfo.imageLengthXZ-(inputInfo.maxZ+displayInfo.geoDeltaZ+displayInfo.padCoronal_Z)+.5,...
                inputInfo.maxX-inputInfo.minX+1, inputInfo.maxZ-inputInfo.minZ+1],...
                'EdgeColor','r');
            hImages.Coronal.center = rectangle('Parent',hImages.hCrlImage,'position',...
                [inputInfo.ctrX+displayInfo.geoDeltaX+displayInfo.padCoronal_X-3/2,...
                displayInfo.imageLengthXZ-(inputInfo.ctrZ+displayInfo.geoDeltaZ+displayInfo.padCoronal_Z)+1-3/2,...
                3, 3],'EdgeColor','y','FaceColor','y');

            hImages.Coronal.slice = createFOVOverlay(hImages.hCrlImage,tempBool,...
                getDisplayedFOVPosition('Coronal',selectView,inputInfo,displayInfo,is3DRadOverlay));

        case 2
            hImages.Axial.volume = rectangle('Parent',hImages.hAxlImage,'position',...
                [inputInfo.minX+displayInfo.geoDeltaX+displayInfo.padAxial_X-.5,...
                displayInfo.imageLengthXY-(inputInfo.maxY+displayInfo.geoDeltaY+displayInfo.padAxial_Y)+.5,...
                inputInfo.maxX-inputInfo.minX+1, inputInfo.maxY-inputInfo.minY+1],...
                'EdgeColor','r');
            hImages.Axial.center = rectangle('Parent',hImages.hAxlImage,'position',...
                [inputInfo.ctrX+displayInfo.geoDeltaX+displayInfo.padAxial_X-3/2,...
                displayInfo.imageLengthXY-(inputInfo.ctrY+displayInfo.geoDeltaY+displayInfo.padAxial_Y)+1-3/2,...
                3, 3],'EdgeColor','y','FaceColor','y');

            hImages.Axial.slice = createFOVOverlay(hImages.hAxlImage,tempBool,...
                getDisplayedFOVPosition('Axial',selectView,inputInfo,displayInfo,is3DRadOverlay));

            hImages.Sagittal.volume = rectangle('Parent',hImages.hSagImage,'position',...
                [inputInfo.minY+displayInfo.geoDeltaY+displayInfo.padSagittal_Y-.5,...
                displayInfo.imageLengthYZ-(inputInfo.maxZ+displayInfo.geoDeltaZ+displayInfo.padSagittal_Z)+.5,...
                inputInfo.maxY-inputInfo.minY+1, inputInfo.maxZ-inputInfo.minZ+1],...
                'EdgeColor','r');
            hImages.Sagittal.center = rectangle('Parent',hImages.hSagImage,'position',...
                [inputInfo.ctrY+displayInfo.geoDeltaY+displayInfo.padSagittal_Y-3/2,...
                displayInfo.imageLengthYZ-(inputInfo.ctrZ+displayInfo.geoDeltaZ+displayInfo.padSagittal_Z)+1-3/2,...
                3, 3],'EdgeColor','y','FaceColor','y');

            hImages.Sagittal.slice = createFOVOverlay(hImages.hSagImage,tempBool,...
                getDisplayedFOVPosition('Sagittal',selectView,inputInfo,displayInfo,is3DRadOverlay));

            hImages.Coronal.volume = rectangle('Parent',hImages.hCrlImage,'position',...
                [inputInfo.minX+displayInfo.geoDeltaX+displayInfo.padCoronal_X-.5,...
                displayInfo.imageLengthXZ-(inputInfo.maxZ+displayInfo.geoDeltaZ+displayInfo.padCoronal_Z)+.5,...
                inputInfo.maxX-inputInfo.minX+1, inputInfo.maxZ-inputInfo.minZ+1],...
                'EdgeColor','r');
            hImages.Coronal.center = rectangle('Parent',hImages.hCrlImage,'position',...
                [inputInfo.ctrX+displayInfo.geoDeltaX+displayInfo.padCoronal_X-3/2,...
                displayInfo.imageLengthXZ-(inputInfo.ctrZ+displayInfo.geoDeltaZ+displayInfo.padCoronal_Z)+1-3/2,...
                3, 3],'EdgeColor','y','FaceColor','y');

            hImages.Coronal.slice = createFOVOverlay(hImages.hCrlImage,tempBool,...
                getDisplayedFOVPosition('Coronal',selectView,inputInfo,displayInfo,is3DRadOverlay));

        case 3
            hImages.Axial.volume = rectangle('Parent',hImages.hAxlImage,'position',...
                [inputInfo.minX+displayInfo.geoDeltaX+displayInfo.padAxial_X-.5,...
                displayInfo.imageLengthXY-(inputInfo.maxY+displayInfo.geoDeltaY+displayInfo.padAxial_Y)+.5,...
                inputInfo.maxX-inputInfo.minX+1, inputInfo.maxY-inputInfo.minY+1],...
                'EdgeColor','r');
            hImages.Axial.center = rectangle('Parent',hImages.hAxlImage,'position',...
                [inputInfo.ctrX+displayInfo.geoDeltaX+displayInfo.padAxial_X-3/2,...
                displayInfo.imageLengthXY-(inputInfo.ctrY+displayInfo.geoDeltaY+displayInfo.padAxial_Y)+1-3/2,...
                3, 3],'EdgeColor','y','FaceColor','y');

            hImages.Axial.slice = createFOVOverlay(hImages.hAxlImage,tempBool,...
                getDisplayedFOVPosition('Axial',selectView,inputInfo,displayInfo,is3DRadOverlay));

            hImages.Sagittal.volume = rectangle('Parent',hImages.hSagImage,'position',...
                [inputInfo.minY+displayInfo.geoDeltaY+displayInfo.padSagittal_Y-.5,...
                displayInfo.imageLengthYZ-(inputInfo.maxZ+displayInfo.geoDeltaZ+displayInfo.padSagittal_Z)+.5,...
                inputInfo.maxY-inputInfo.minY+1, inputInfo.maxZ-inputInfo.minZ+1],...
                'EdgeColor','r');
            hImages.Sagittal.center = rectangle('Parent',hImages.hSagImage,'position',...
                [inputInfo.ctrY+displayInfo.geoDeltaY+displayInfo.padSagittal_Y-3/2,...
                displayInfo.imageLengthYZ-(inputInfo.ctrZ+displayInfo.geoDeltaZ+displayInfo.padSagittal_Z)+1-3/2,...
                3, 3],'EdgeColor','y','FaceColor','y');

            hImages.Sagittal.slice = createFOVOverlay(hImages.hSagImage,tempBool,...
                getDisplayedFOVPosition('Sagittal',selectView,inputInfo,displayInfo,is3DRadOverlay));

            hImages.Coronal.volume = rectangle('Parent',hImages.hCrlImage,'position',...
                [inputInfo.minX+displayInfo.geoDeltaX+displayInfo.padCoronal_X-.5,...
                displayInfo.imageLengthXZ-(inputInfo.maxZ+displayInfo.geoDeltaZ+displayInfo.padCoronal_Z)+.5,...
                inputInfo.maxX-inputInfo.minX+1, inputInfo.maxZ-inputInfo.minZ+1],...
                'EdgeColor','r');
            hImages.Coronal.center = rectangle('Parent',hImages.hCrlImage,'position',...
                [inputInfo.ctrX+displayInfo.geoDeltaX+displayInfo.padCoronal_X-3/2,...
                displayInfo.imageLengthXZ-(inputInfo.ctrZ+displayInfo.geoDeltaZ+displayInfo.padCoronal_Z)+1-3/2,...
                3, 3],'EdgeColor','y','FaceColor','y');

            hImages.Coronal.slice = createFOVOverlay(hImages.hCrlImage,tempBool,...
                getDisplayedFOVPosition('Coronal',selectView,inputInfo,displayInfo,is3DRadOverlay));
    end
    if inputInfo.FOV_flag==1
        inputInfo.FOV=rot90(inputInfo.FOV,2);
    end
end

function hOverlay = createFOVOverlay(axisHandle,hideOverlay,position)
    if hideOverlay
        hOverlay = rectangle('Parent',axisHandle,'Visible','off');
    else
        hOverlay = rectangle('Parent',axisHandle,'position',position,'EdgeColor','g');
    end
end

function position = getDisplayedFOVPosition(panelName,selectView,inputInfo,displayInfo,is3DRadOverlay)
    if is3DRadOverlay
        position = get3DRadFOVPosition(panelName,inputInfo,displayInfo);
        return;
    end

    switch selectView
        case 1
            switch panelName
                case 'Axial'
                    position = [inputInfo.ctrX+inputInfo.setX+displayInfo.geoDeltaX+displayInfo.padAxial_X-inputInfo.FOV(1)/inputInfo.widX/2,...
                        displayInfo.imageLengthXY-(inputInfo.ctrY+inputInfo.setY+displayInfo.geoDeltaY+displayInfo.padAxial_Y)+1-inputInfo.FOV(2)/inputInfo.widY/2,...
                        inputInfo.FOV(1)/inputInfo.widX, inputInfo.FOV(2)/inputInfo.widY];
                case 'Sagittal'
                    position = [inputInfo.ctrY+inputInfo.setY+displayInfo.geoDeltaY+displayInfo.padSagittal_Y-inputInfo.FOV(2)/inputInfo.widY/2,...
                        displayInfo.imageLengthYZ-(inputInfo.currentZ+displayInfo.geoDeltaZ+displayInfo.padSagittal_Z)+1-inputInfo.sliceTH/inputInfo.widZ/2,...
                        inputInfo.FOV(2)/inputInfo.widY, inputInfo.sliceTH/inputInfo.widZ];
                case 'Coronal'
                    position = [inputInfo.ctrX+inputInfo.setX+displayInfo.geoDeltaX+displayInfo.padCoronal_X-inputInfo.FOV(1)/inputInfo.widX/2,...
                        displayInfo.imageLengthXZ-(inputInfo.currentZ+displayInfo.geoDeltaZ+displayInfo.padCoronal_Z)+1-inputInfo.sliceTH/inputInfo.widZ/2,...
                        inputInfo.FOV(1)/inputInfo.widX, inputInfo.sliceTH/inputInfo.widZ];
            end

        case 2
            switch panelName
                case 'Axial'
                    position = [inputInfo.currentX+displayInfo.geoDeltaX+displayInfo.padAxial_X-inputInfo.sliceTH/inputInfo.widX/2,...
                        displayInfo.imageLengthXY-(inputInfo.ctrY+inputInfo.setY+displayInfo.geoDeltaY+displayInfo.padAxial_Y)+1-inputInfo.FOV(1)/inputInfo.widY/2,...
                        inputInfo.sliceTH/inputInfo.widX,inputInfo.FOV(1)/inputInfo.widY];
                case 'Sagittal'
                    position = [inputInfo.ctrY+inputInfo.setY+displayInfo.geoDeltaY+displayInfo.padSagittal_Y-inputInfo.FOV(1)/inputInfo.widY/2,...
                        displayInfo.imageLengthYZ-(inputInfo.ctrZ+inputInfo.setZ+displayInfo.geoDeltaZ+displayInfo.padSagittal_Z)+1-inputInfo.FOV(2)/inputInfo.widZ/2,...
                        inputInfo.FOV(1)/inputInfo.widY, inputInfo.FOV(2)/inputInfo.widZ];
                case 'Coronal'
                    position = [inputInfo.currentX+displayInfo.geoDeltaX+displayInfo.padCoronal_X-inputInfo.sliceTH/inputInfo.widX/2,...
                        displayInfo.imageLengthXZ-(inputInfo.ctrZ+inputInfo.setZ+displayInfo.geoDeltaZ+displayInfo.padCoronal_Z)+1-inputInfo.FOV(2)/inputInfo.widZ/2,...
                        inputInfo.sliceTH/inputInfo.widX, inputInfo.FOV(2)/inputInfo.widZ];
            end

        case 3
            switch panelName
                case 'Axial'
                    position = [inputInfo.ctrX+inputInfo.setX+displayInfo.geoDeltaX+displayInfo.padAxial_X-inputInfo.FOV(1)/inputInfo.widX/2,...
                        displayInfo.imageLengthXY-(inputInfo.currentY+displayInfo.geoDeltaY+displayInfo.padAxial_Y)+1-inputInfo.sliceTH/inputInfo.widY/2,...
                        inputInfo.FOV(1)/inputInfo.widX, inputInfo.sliceTH/inputInfo.widY];
                case 'Sagittal'
                    position = [inputInfo.currentY+displayInfo.geoDeltaY+displayInfo.padSagittal_Y-inputInfo.sliceTH/inputInfo.widY/2,...
                        displayInfo.imageLengthYZ-(inputInfo.ctrZ+inputInfo.setZ+displayInfo.geoDeltaZ+displayInfo.padSagittal_Z)+1-inputInfo.FOV(2)/inputInfo.widZ/2,...
                        inputInfo.sliceTH/inputInfo.widY,inputInfo.FOV(2)/inputInfo.widZ];
                case 'Coronal'
                    position = [inputInfo.ctrX+inputInfo.setX+displayInfo.geoDeltaX+displayInfo.padCoronal_X-inputInfo.FOV(1)/inputInfo.widX/2,...
                        displayInfo.imageLengthXZ-(inputInfo.ctrZ+inputInfo.setZ+displayInfo.geoDeltaZ+displayInfo.padCoronal_Z)+1-inputInfo.FOV(2)/inputInfo.widZ/2,...
                        inputInfo.FOV(1)/inputInfo.widX, inputInfo.FOV(2)/inputInfo.widZ];
            end
    end
end

function position = get3DRadFOVPosition(panelName,inputInfo,displayInfo)
    radialFOV = max([inputInfo.FOV(:).',1]);
    radialX = radialFOV / inputInfo.widX;
    radialY = radialFOV / inputInfo.widY;
    radialZ = radialFOV / inputInfo.widZ;
    centerX = inputInfo.ctrX + getOffsetValue(inputInfo,'setX');
    centerY = inputInfo.ctrY + getOffsetValue(inputInfo,'setY');
    centerZ = inputInfo.ctrZ + getOffsetValue(inputInfo,'setZ');

    switch panelName
        case 'Axial'
            position = [centerX+displayInfo.geoDeltaX+displayInfo.padAxial_X-radialX/2,...
                displayInfo.imageLengthXY-(centerY+displayInfo.geoDeltaY+displayInfo.padAxial_Y)+1-radialY/2,...
                radialX, radialY];
        case 'Sagittal'
            position = [centerY+displayInfo.geoDeltaY+displayInfo.padSagittal_Y-radialY/2,...
                displayInfo.imageLengthYZ-(centerZ+displayInfo.geoDeltaZ+displayInfo.padSagittal_Z)+1-radialZ/2,...
                radialY, radialZ];
        case 'Coronal'
            position = [centerX+displayInfo.geoDeltaX+displayInfo.padCoronal_X-radialX/2,...
                displayInfo.imageLengthXZ-(centerZ+displayInfo.geoDeltaZ+displayInfo.padCoronal_Z)+1-radialZ/2,...
                radialX, radialZ];
    end
end

function value = getOffsetValue(inputInfo,fieldName)
    if isfield(inputInfo,fieldName)
        value = inputInfo.(fieldName);
    else
        value = 0;
    end
end

function renderSlice(ax, imageMatrix)
    cla(ax);
    imagesc(ax, imageMatrix);
    axis(ax, 'image');
    axis(ax, 'off');
    colormap(ax, gray);
end

function index = clampIndex(index, maxIndex)
    index = round(index);
    index = min(max(index, 1), maxIndex);
end

function paddedMatrix = padWithZeros(inputMatrix, padSize)
    inputSize = size(inputMatrix);
    paddedMatrix = zeros(inputSize + 2 .* padSize);
    rowIndex = (1:inputSize(1)) + padSize(1);
    colIndex = (1:inputSize(2)) + padSize(2);
    paddedMatrix(rowIndex, colIndex) = inputMatrix;
end
