function [command, argumentText] = buildRunCommand(runType, executable, inputs)
%BUILDRUNCOMMAND Format a prepared run for the batch file and Simulation Jobs.
% Inputs contain resolved paths and the original text from the run controls.

common = [runArgument('GeometryFile', inputs.geometryFile), ...
    runArgument('TissueTypeFile', inputs.tissueFile), ...
    runArgument('SequenceFile', inputs.sequenceFile)];
switch runType
    case 'Signal'
        argumentText = [runArgument('NumIso', inputs.numIso), ...
            runArgument('Thread', inputs.threads), ...
            runArgument('B0', inputs.b0), ...
            runArgument('Nucleus', inputs.nucleus), common, ...
            fileArguments('DelB0File', {inputs.deltaB0File}), ...
            fileArguments('B1PlusFile', inputs.transmitB1Files), ...
            fileArguments('B1MinsFile', inputs.receiveB1Files), ...
            fileArguments('DelGxFile', {inputs.deltaGxFile}), ...
            fileArguments('DelGyFile', {inputs.deltaGyFile}), ...
            fileArguments('DelGzFile', {inputs.deltaGzFile}), ...
            runArgument('KSpaceFile', inputs.kSpaceFile), ...
            runArgument('KMapFile', inputs.kMapFile), ...
            sampleBoundsArguments(inputs.sampleBounds), ...
            runArgument('xCtr', inputs.xCenter), ...
            runArgument('yCtr', inputs.yCenter), ...
            runArgument('zCtr', inputs.zCenter)];
    case 'SAR'
        argumentText = [runArgument('Thread', inputs.threads), common, ...
            fileArguments('B1PlusFile', inputs.transmitB1Files), ...
            fileArguments('E1PlusFile', inputs.transmitE1Files), ...
            fileArguments('B1MinsFile', inputs.receiveB1Files), ...
            runArgument('SARFile', inputs.sarFile), ...
            sampleBoundsArguments(inputs.sampleBounds)];
    case 'Noise'
        argumentText = [runArgument('NEX', inputs.nex), ...
            runArgument('Nucleus', inputs.nucleus), ...
            runArgument('NoiseSeed', inputs.noiseSeed), common, ...
            fileArguments('E1MinsFile', inputs.receiveE1Files), ...
            runArgument('KNoiseFile', inputs.noiseFile), ...
            noiseLoadingArguments(inputs.noiseLoading)];
    otherwise
        error('buildRunCommand:UnknownRunType', 'Unknown run type "%s".', runType);
end
command = ['"', executable, '"', argumentText];
end

function text = runArgument(key, value)
text = [' "', key, '=', value, '"'];
end

function text = fileArguments(key, files)
text = '';
for n = 1:numel(files)
    if ~isempty(files{n})
        text = [text, runArgument(key, files{n})]; %#ok<AGROW>
    end
end
end

function text = sampleBoundsArguments(bounds)
text = [runArgument('xMin', bounds.xMin), runArgument('xMax', bounds.xMax), ...
    runArgument('yMin', bounds.yMin), runArgument('yMax', bounds.yMax), ...
    runArgument('zMin', bounds.zMin), runArgument('zMax', bounds.zMax)];
end
